const Quiz = (() => {
  let pool = [];

  function refill() {
    pool = QUESTIONS.map((_, i) => i);
    for (let i = pool.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [pool[i], pool[j]] = [pool[j], pool[i]];
    }
  }

  /** 한 판에서 같은 문제가 연속으로 나오지 않게 섞어 뽑는다 */
  function next() {
    if (!pool.length) refill();
    return QUESTIONS[pool.pop()];
  }

  function reset() { pool = []; }

  return { next, reset };
})();
