const Quiz = (() => {
  let current = null;
  let answered = false;

  function pick(stageId) {
    const pool = QUIZZES[stageId] || QUIZZES[1];
    return pool[Math.floor(Math.random() * pool.length)];
  }

  function start(stageId, onDone) {
    current = pick(stageId);
    answered = false;
    return { question: current, done: onDone };
  }

  function check(i) {
    if (!current || answered) return null;
    answered = true;
    return { correct: i === current.a, answer: current.a, why: current.why };
  }

  function isAnswered() { return answered; }
  function get() { return current; }

  return { start, check, isAnswered, get };
})();
